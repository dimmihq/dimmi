/*
|--------------------------------------------------------------------------
| Classifier
|--------------------------------------------------------------------------
|
| Before anything answers a received email, it is sorted: our own mail
| coming back, a notice from a mail system, a bounce or complaint, an
| out-of-office reply, spam, a teammate forwarding or testing, a
| mailing list, bulk mail, a notification from a no-reply sender, or a
| person writing. The first rule that matches wins, in that order.
|
| Automatic mail is recognized by the headers RFC 3834 and the big mail
| systems set. A subject such as "Out of Office" alone is not enough,
| since people write those words too; it counts only beside a header
| signal or on a short message.
|
*/

package email

import (
	"regexp"
	"strings"

	"github.com/dimmihq/dimmi/app/enums"
)

/*
shortAutoReplyBody is the longest visible body a subject-only
auto-reply may have.
*/
const shortAutoReplyBody = 1000

var (
	autoReplySubject = regexp.MustCompile(`(?i)^\s*(out of (the )?office|automatic reply|auto[- ]?reply|` +
		`autoreply|abwesenheitsnotiz|réponse automatique|respuesta automática|risposta automatica|fuori sede|` +
		`automatisch antwoord|afwezig|resposta automática|odpowiedź automatyczna|自動返信|自动回复|자동 응답)`)
	noreplyLocal = regexp.MustCompile(`^(no-?reply|do-?not-?reply|notifications?|mailer|bounces?|alerts?|` +
		`automated)([-+._].*)?$`)
	bounceSubject = regexp.MustCompile(`(?i)(undeliverable|undelivered mail|delivery status notification|` +
		`mail delivery failed|returned mail|delivery failure|unzustellbar|non remis|failure notice)`)
)

/*
Header is the header of a received message, read by canonical name.
*/
type Header interface {
	/*
		Get returns the first value of the field, or "".
	*/
	Get(key string) string
}

/*
Signals is what is known about a received message when it is sorted.

Loop means it is our own mail coming back. SystemNotice means a mail
system's own notice to the address, such as a forwarding confirmation.
Complaint and Bounce mean a feedback or delivery report. Spam means a
provider or policy condemned it. Member means an active teammate sent
it, authenticated; Forwarded that it carries a forwarded message.
FormRelay means a form service sent it on a customer's behalf.
VisibleChars is the length of the body as the customer wrote it.
*/
type Signals struct {
	Header       Header
	Subject      string
	From         string
	VisibleChars int
	Loop         bool
	SystemNotice bool
	Complaint    bool
	Bounce       bool
	Spam         bool
	Member       bool
	Forwarded    bool
	FormRelay    bool
}

/*
Classify returns the kind of the message: the first rule that matches.
*/
func Classify(s Signals) enums.EmailClassification {
	rules := []struct {
		match bool
		class enums.EmailClassification
	}{
		{s.Loop, enums.EmailClassificationLoop},
		{s.SystemNotice, enums.EmailClassificationSystemNotice},
		{s.Complaint, enums.EmailClassificationComplaint},
		{s.Bounce, enums.EmailClassificationBounce},
		{AutoReply(s.Header, s.Subject, s.VisibleChars), enums.EmailClassificationAutoReply},
		{s.Spam, enums.EmailClassificationSpam},
		{s.Member && s.Forwarded, enums.EmailClassificationForwarded},
		{s.Member, enums.EmailClassificationTest},
		{List(s.Header), enums.EmailClassificationList},
		{Bulk(s.Header), enums.EmailClassificationBulk},
		{!s.FormRelay && Noreply(s.From), enums.EmailClassificationNoreply},
	}

	for _, rule := range rules {
		if rule.match {
			return rule.class
		}
	}

	return enums.EmailClassificationNormal
}

/*
AutoReply reports whether the message is an automatic reply: a header
signal, or an auto-reply subject on a short message.
*/
func AutoReply(h Header, subject string, visibleChars int) bool {
	if autoReplyHeader(h) {
		return true
	}

	return autoReplySubject.MatchString(subject) && visibleChars < shortAutoReplyBody
}

/*
autoReplyHeader reports whether a header field marks the message as
sent by a machine in reply.
*/
func autoReplyHeader(h Header) bool {
	submitted := strings.ToLower(strings.TrimSpace(h.Get("Auto-Submitted")))
	precedence := strings.ToLower(h.Get("Precedence") + " " + h.Get("X-Precedence"))

	return (submitted != "" && submitted != "no") ||
		h.Get("X-Autoreply") != "" || h.Get("X-Autorespond") != "" ||
		strings.EqualFold(strings.TrimSpace(h.Get("X-Autogenerated")), "reply") ||
		strings.Contains(precedence, "auto_reply") ||
		h.Get("X-MS-Exchange-Inbox-Rules-Loop") != "" ||
		strings.Contains(strings.ToLower(h.Get("X-POST-MessageClass")), "autoresponder")
}

/*
List reports whether a mailing list delivered the message.
*/
func List(h Header) bool {
	return h.Get("List-Id") != "" || h.Get("List-Post") != "" || h.Get("X-Mailman-Version") != "" ||
		h.Get("X-Google-Group-Id") != "" || h.Get("Mailing-List") != "" ||
		strings.EqualFold(strings.TrimSpace(h.Get("Precedence")), "list")
}

/*
Bulk reports whether the message is bulk mail: marked so, or carrying an
unsubscribe link beside a sending service's campaign headers.
*/
func Bulk(h Header) bool {
	precedence := strings.ToLower(strings.TrimSpace(h.Get("Precedence")))
	if precedence == "bulk" || precedence == "junk" {
		return true
	}

	if h.Get("List-Unsubscribe") == "" {
		return false
	}

	for _, field := range []string{
		"Feedback-ID", "X-Mailgun-Tag", "X-SG-EID", "X-SES-Outgoing", "X-Mailchimp-Campaign", "X-Campaign",
		"X-MC-User", "X-Postmark-Stream",
	} {
		if h.Get(field) != "" {
			return true
		}
	}

	return false
}

/*
Noreply reports whether the sender's address says nobody reads replies
to it.
*/
func Noreply(from string) bool {
	local, _, _ := strings.Cut(strings.ToLower(from), "@")

	return noreplyLocal.MatchString(local)
}

/*
BounceNotice reports whether a message without a delivery report still
reads as one: sent by a mail system, with a failure subject.
*/
func BounceNotice(envelopeFrom, from, subject string) bool {
	local, _, _ := strings.Cut(strings.ToLower(from), "@")
	system := envelopeFrom == "" || local == "mailer-daemon" || local == "postmaster"

	return system && bounceSubject.MatchString(subject)
}
