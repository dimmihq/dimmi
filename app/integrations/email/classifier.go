/*
|--------------------------------------------------------------------------
| Classifier
|--------------------------------------------------------------------------
|
| Before anything answers a received email, it is sorted: our own mail
| coming back, a notice from a mail system, a bounce or complaint, an
| out-of-office reply, spam, a teammate forwarding or testing, a
| mailing list, bulk mail, a notification from a no-reply sender, or a
| person writing. The first rule that matches wins, in that order.
|
| Automatic mail is recognized by the headers RFC 3834 and the big mail
| systems set, read for their value, so "X-Autoreply: no" is a person.
| A read receipt is an automatic reply too, so it never wakes a thread.
| An automatic reply answers someone; other machine mail, such as a
| notification marked auto-generated, is filed like bulk mail and kept,
| never dropped as a reply. A subject such as "Out of Office" alone is
| never enough to discard a first message, since people write those
| words too: it only keeps a short mail on an existing thread quiet.
|
*/

package email

import (
	"regexp"
	"strings"

	"github.com/dimmihq/dimmi/app/enums"
)

/*
shortAutoReplyBody is the longest visible body a subject-only
auto-reply may have.
*/
const shortAutoReplyBody = 1000

var (
	autoReplySubject = regexp.MustCompile(`(?i)^\s*((re|aw|sv|antw|wg|fw|fwd)\s*:\s*)*(out of (the )?office|` +
		`automatic reply|auto[- ]?reply|autoreply|auto:|autosvar|automatisk svar|automaattinen vastaus|` +
		`автоответ|abwesend|abwesenheitsnotiz|vacation reply|on vacation|réponse automatique|` +
		`respuesta automática|risposta automatica|fuori sede|automatisch antwoord|afwezig|resposta automática|` +
		`odpowiedź automatyczna|自動返信|自动回复|자동 응답)`)
	noreplyLocal = regexp.MustCompile(`^(.*[-_.+])?(no[-_.]?reply|do[-_.]?not[-_.]?reply)([-_.+].*)?$|` +
		`^(notifications?|mailer|postmaster|bounces?|alerts?|automated)([-+._].*)?$`)
	bounceSubject = regexp.MustCompile(`(?i)(undeliverable|undelivered mail|delivery status notification|` +
		`mail delivery failed|returned mail|delivery failure|delivery has failed|message not delivered|` +
		`could not be delivered|unzustellbar|nicht zustellbar|zustellung fehlgeschlagen|non remis|` +
		`non recapitabile|no se puede entregar|não entregue|failure notice)`)
)

/*
Header is the header of a received message, read by canonical name.
*/
type Header interface {
	/*
		Get returns the first value of the field, or "".
	*/
	Get(key string) string
}

/*
Signals is what is known about a received message when it is sorted.

Loop means it is our own mail coming back. SystemNotice means a mail
system's own notice to the address, such as a forwarding confirmation.
Complaint and Bounce mean a feedback or delivery report. Spam means a
provider or policy condemned it. Member means an active teammate sent
it, authenticated; Forwarded that it carries a forwarded message.
FormRelay means a form service sent it on a customer's behalf, and
GroupRelay that the workspace's own group address sent a customer's
mail on, which makes its list headers the group's, not a list's.
*/
type Signals struct {
	Header       Header
	From         string
	Loop         bool
	SystemNotice bool
	Complaint    bool
	Bounce       bool
	Spam         bool
	Member       bool
	Forwarded    bool
	FormRelay    bool
	GroupRelay   bool
}

/*
Classify returns the kind of the message: the first rule that matches.
*/
func Classify(s Signals) enums.EmailClassification {
	rules := []struct {
		match bool
		class enums.EmailClassification
	}{
		{s.Loop, enums.EmailClassificationLoop},
		{s.SystemNotice, enums.EmailClassificationSystemNotice},
		{s.Complaint, enums.EmailClassificationComplaint},
		{s.Bounce, enums.EmailClassificationBounce},
		{AutoReply(s.Header), enums.EmailClassificationAutoReply},
		{s.Spam, enums.EmailClassificationSpam},
		{s.Member && s.Forwarded, enums.EmailClassificationForwarded},
		{s.Member, enums.EmailClassificationTest},
		{!s.GroupRelay && List(s.Header), enums.EmailClassificationList},
		{Bulk(s.Header) || (!s.FormRelay && AutoGenerated(s.Header)), enums.EmailClassificationBulk},
		{!s.FormRelay && Noreply(s.From), enums.EmailClassificationNoreply},
	}

	for _, rule := range rules {
		if rule.match {
			return rule.class
		}
	}

	return enums.EmailClassificationNormal
}

/*
AutoReply reports whether a header field marks the message as sent by
a machine in reply to someone, such as an out-of-office answer.
*/
func AutoReply(h Header) bool {
	precedence := strings.ToLower(h.Get("Precedence") + " " + h.Get("X-Precedence"))

	return strings.HasPrefix(submitted(h), "auto-replied") || readReceipt(h) ||
		anyOn(h, "X-Autoreply", "X-Autorespond", "X-Autoresponse", "X-Autoresponder", "X-Mail-Autoreply",
			"X-Vacation", "X-Loop") ||
		strings.EqualFold(strings.TrimSpace(h.Get("X-Autogenerated")), "reply") ||
		strings.Contains(precedence, "auto_reply") ||
		h.Get("X-MS-Exchange-Inbox-Rules-Loop") != "" ||
		strings.Contains(strings.ToLower(h.Get("X-MS-Exchange-Generated-Message-Source")), "mailbox rules agent") ||
		strings.Contains(strings.ToLower(h.Get("X-POST-MessageClass")), "autoresponder")
}

/*
readReceipt reports whether the message is a mail client's notice that
a message was read or deleted.
*/
func readReceipt(h Header) bool {
	kind := strings.ToLower(strings.Join(strings.Fields(strings.ReplaceAll(h.Get("Content-Type"), `"`, "")), ""))

	return strings.HasPrefix(kind, "multipart/report;") &&
		strings.Contains(kind, ";report-type=disposition-notification")
}

/*
AutoGenerated reports whether the message says a machine wrote it
without answering anyone, such as a notification or a monitor's alert.
*/
func AutoGenerated(h Header) bool {
	value := submitted(h)

	return value != "" && value != "no" && !strings.HasPrefix(value, "auto-replied")
}

/*
AutoReplySubject reports whether a short message's subject reads like
an automatic reply. It is a hint, never a reason to discard a message.
*/
func AutoReplySubject(subject string, visibleChars int) bool {
	return autoReplySubject.MatchString(subject) && visibleChars < shortAutoReplyBody
}

/*
submitted returns the Auto-Submitted field, lowercased.
*/
func submitted(h Header) string {
	return strings.ToLower(strings.TrimSpace(h.Get("Auto-Submitted")))
}

/*
anyOn reports whether any of the fields is present with a value that
does not switch it off, such as "no", "0" or "false".
*/
func anyOn(h Header, fields ...string) bool {
	for _, field := range fields {
		switch strings.ToLower(strings.TrimSpace(h.Get(field))) {
		case "", "no", "0", "false", "off", "none":
			continue
		default:
			return true
		}
	}

	return false
}

/*
List reports whether a mailing list delivered the message.
*/
func List(h Header) bool {
	return h.Get("List-Id") != "" || h.Get("List-Post") != "" || h.Get("X-Mailman-Version") != "" ||
		h.Get("X-Google-Group-Id") != "" || h.Get("Mailing-List") != "" ||
		strings.EqualFold(strings.TrimSpace(h.Get("Precedence")), "list")
}

/*
Bulk reports whether the message is bulk mail: marked so, or carrying an
unsubscribe link beside a sending service's campaign headers.
*/
func Bulk(h Header) bool {
	precedence := strings.ToLower(strings.TrimSpace(h.Get("Precedence")))
	if precedence == "bulk" || precedence == "junk" {
		return true
	}

	if h.Get("List-Unsubscribe") == "" {
		return false
	}

	for _, field := range []string{
		"Feedback-ID", "X-Mailgun-Tag", "X-SG-EID", "X-SES-Outgoing", "X-Mailchimp-Campaign", "X-Campaign",
		"X-MC-User", "X-Postmark-Stream",
	} {
		if h.Get(field) != "" {
			return true
		}
	}

	return false
}

/*
Noreply reports whether the sender's address says nobody reads replies
to it.
*/
func Noreply(from string) bool {
	local, _, _ := strings.Cut(strings.ToLower(from), "@")

	return noreplyLocal.MatchString(local)
}

/*
BounceNotice reports whether a message without a readable delivery
report still reads as one: sent by a mail system, naming the addresses
that failed, or sent with no return address under a failure subject.
*/
func BounceNotice(h Header, envelopeFrom, from, subject string) bool {
	local, _, _ := strings.Cut(strings.ToLower(from), "@")
	if local == "mailer-daemon" || local == "postmaster" || strings.TrimSpace(h.Get("X-Failed-Recipients")) != "" {
		return true
	}

	return envelopeFrom == "" && bounceSubject.MatchString(subject)
}
