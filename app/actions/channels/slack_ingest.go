/*
|--------------------------------------------------------------------------
| Slack Messages Into The Inbox
|--------------------------------------------------------------------------
|
| A Slack message becomes an inbound message for the inbox: its author
| as a contact known by their Slack id, its text as Markdown, its files
| downloaded from Slack's own hosts, and the thread it continues. Every
| message is recognized by its channel and timestamp, so a retry, the
| same message over a socket and a webhook, or a message opened again by
| hand never lands twice. A message in a channel others read is marked
| public, so the agent answers there from knowledge only.
|
| A file larger than the inbox accepts is not downloaded; the message
| says which file it was instead.
|
*/

package channels

import (
	"context"
	"errors"
	"fmt"
	"io"
	"strconv"
	"strings"
	"time"

	"github.com/dimmihq/dimmi/framework/database"

	"github.com/dimmihq/dimmi/app/actions/conversations"
	"github.com/dimmihq/dimmi/app/contracts"
	slackdriver "github.com/dimmihq/dimmi/app/drivers/channel/slack"
	"github.com/dimmihq/dimmi/app/enums"
	"github.com/dimmihq/dimmi/app/models"
)

/*
maxInboundFileBytes is the largest Slack file the inbox downloads.
*/
const maxInboundFileBytes = 25 << 20

/*
ingestion is one Slack message on its way into the inbox: the
connection, the room it was written in, nil for a direct message, the
message, who wrote it, the thread key it belongs to and the trigger
that let it in. Quiet marks a pleasantry, stored without waking anyone;
Echo a linked teammate's own reply; Test a teammate trying their own
bot.
*/
type ingestion struct {
	conn      models.ChannelConnection
	room      *models.ChannelRoom
	ev        slackdriver.Event
	author    author
	threadKey string
	trigger   enums.RoomTrigger
	quiet     bool
	echo      bool
	test      bool
	opening   contracts.BeforeFirst
}

/*
ingest hands the message to the inbox, reporting false when the inbox
had no place for it: an echo outside any conversation, or a connection
gone meanwhile.
*/
func (s *Slack) ingest(ctx context.Context, in ingestion) (contracts.InboundResult, bool, error) {
	msg, err := s.inbound(ctx, in)
	if err != nil {
		return contracts.InboundResult{}, false, err
	}

	result, err := s.Receiver.ReceiveInboundMessage(ctx, msg)
	if errors.Is(err, conversations.ErrEchoWithoutConversation) || errors.Is(err, conversations.ErrConnectionGone) {
		return result, false, nil
	}

	if err != nil {
		return result, false, fmt.Errorf("receive slack message: %w", err)
	}

	return result, true, nil
}

/*
inbound shapes the inbound message.
*/
func (s *Slack) inbound(ctx context.Context, in ingestion) (contracts.InboundMessage, error) {
	channel, facts := in.ev.ChannelID(), FactsOf(in.conn)
	body := slackdriver.ToMarkdown(in.ev.Text, in.ev.Blocks, s.names(ctx, in.conn))
	files, skipped, err := s.files(ctx, in.conn, in.ev.Files)
	if err != nil {
		return contracts.InboundMessage{}, err
	}

	if len(skipped) > 0 {
		body = strings.TrimSpace(body + "\n\n" + strings.Join(skipped, "\n"))
	}

	msg := contracts.InboundMessage{
		ConnectionID: in.conn.ID, DedupeKey: slackdriver.DedupeKey(facts.TeamID, channel, in.ev.TS),
		ExternalThreadKey: in.threadKey, Body: body, BodyFormat: enums.BodyFormatMarkdown,
		ChannelMessageID: slackdriver.MessageID(channel, in.ev.TS), SentAt: timeOf(in.ev.TS, s.Clock.Now()),
		Sender: sender(in.author), Attachments: files, AutoGenerated: in.quiet, IsTest: in.test,
		Source: source(in), Metadata: metadataOf(in, channel), FromMemberName: in.author.memberName,
	}

	if in.ev.InThread() {
		msg.ReplyToChannelMessageID = slackdriver.MessageID(channel, in.ev.ThreadTS)
	}

	if in.echo {
		msg.Echo = &contracts.EchoAuthor{MemberID: in.author.memberID}
	}

	if in.test {
		msg.AfterPersist = markTest
	}

	msg.BeforeFirst = in.opening

	return msg, nil
}

/*
markTest marks a conversation a teammate opened with their own app as a
test, in the inbox's transaction, so it is never billed.
*/
func markTest(ctx context.Context, tx *database.Tx, conv models.Conversation, _ models.Message) error {
	if conv.IsTest {
		return nil
	}

	err := models.New(tx).MarkConversationAsTest(ctx, models.MarkConversationAsTestParams{
		WorkspaceID: conv.WorkspaceID, ID: conv.ID,
	})
	if err != nil {
		return fmt.Errorf("mark test conversation: %w", err)
	}

	return nil
}

/*
sender is the author as the inbox's contact: known by their Slack id,
named as Slack shows them, with their Slack email for display only.
Slack lets an organization's admins set any email, so it proves nothing.
*/
func sender(a author) contracts.InboundSender {
	return contracts.InboundSender{
		Identities: []contracts.IdentityClaim{{Type: enums.IdentityTypeSlackUser, Value: a.identity, Verified: true}},
		Name:       a.user.Name, Email: a.user.Email,
	}
}

/*
source describes how a new conversation started: on Slack, by which
trigger, in which room, and whether others read it there.
*/
func source(in ingestion) map[string]any {
	channel := map[string]any{"type": slackdriver.Type, "trigger": string(in.trigger)}
	public := in.room != nil

	if in.room != nil {
		channel["room_id"] = in.room.ID.String()
	}

	out := map[string]any{"channel": channel, "public_room": public}
	if in.room != nil && in.room.CompanyID != nil && in.room.IsSharedExternal {
		out["audience_company_id"] = in.room.CompanyID.String()
	}

	return out
}

/*
metadataOf is what the message keeps of where it was written.
*/
func metadataOf(in ingestion, channel string) map[string]any {
	meta := map[string]any{
		"team": in.author.user.TeamID, "user": in.author.user.ID, "channel": channel, "ts": in.ev.TS,
		"public_room": in.room != nil,
	}

	if in.ev.ThreadTS != "" {
		meta["thread_ts"] = in.ev.ThreadTS
	}

	return meta
}

/*
files returns the message's files to store and a line for each file
too large to download.
*/
func (s *Slack) files(ctx context.Context, conn models.ChannelConnection, shared []slackdriver.File) (
	[]contracts.InboundAttachment, []string, error,
) {
	if len(shared) == 0 {
		return nil, nil, nil
	}

	api, err := s.api(ctx, conn)
	if err != nil {
		return nil, nil, err
	}

	var (
		out     []contracts.InboundAttachment
		skipped []string
	)

	for _, file := range shared {
		if file.Size > maxInboundFileBytes || file.DownloadURL == "" {
			skipped = append(skipped, "["+file.Name+", too large to import]")

			continue
		}

		address := file.DownloadURL
		out = append(out, contracts.InboundAttachment{
			Filename: file.Name, ContentType: file.Mimetype, SizeBytes: file.Size,
			Open: func(ctx context.Context) (io.ReadCloser, error) {
				return api.OpenFile(ctx, address, maxInboundFileBytes)
			},
		})
	}

	return out, skipped, nil
}

/*
timeOf reads a Slack timestamp as a time, or the fallback when it is
not one.
*/
func timeOf(ts string, fallback time.Time) time.Time {
	seconds, _, _ := strings.Cut(ts, ".")

	unix, err := strconv.ParseInt(seconds, 10, 64)
	if err != nil {
		return fallback
	}

	return time.Unix(unix, 0).UTC()
}
