/*
|--------------------------------------------------------------------------
| Inbound Message
|--------------------------------------------------------------------------
|
| A channel hands every message it receives to the inbox in one shape.
| The inbox decides which contact and conversation it belongs to; the
| channel only says what it knows: the connection it arrived on, a key
| that recognizes a redelivery, the thread it continues, who sent it and
| what they can prove, and the message itself. The channel's own rows
| are written by its hook inside the inbox's transaction, so they never
| disagree with the stored message.
|
*/

package contracts

import (
	"context"
	"io"
	"time"

	"github.com/dimmihq/dimmi/framework/database"
	"github.com/dimmihq/dimmi/framework/ids"

	"github.com/dimmihq/dimmi/app/enums"
	"github.com/dimmihq/dimmi/app/models"
)

/*
InboundMessage is one message a channel received.

ConnectionID names the connection it arrived on, which decides the
workspace and inbox. DedupeKey is unique per provider message, so a
redelivery is recognized. ExternalThreadKey is the channel's own thread,
and ConversationID a conversation the channel already knows the message
belongs to. Body is in BodyFormat, Markdown when left empty. BodyFull
is the whole text when Body shows only part of it, and BodyHTML the
provider's HTML. AutoGenerated marks mail nobody wrote by hand, which
never reopens, wakes or notifies. Source describes the start of a new
conversation. Metadata is kept on the message under the channel's type.
AfterPersist, when set, runs in the same transaction right after the
message is stored, so the channel writes its own rows atomically with
it; its error undoes everything.
*/
type InboundMessage struct {
	ConnectionID            ids.UUID
	DedupeKey               string
	ExternalThreadKey       string
	ConversationID          *ids.UUID
	ForceNewConversation    bool
	Sender                  InboundSender
	Participants            []InboundSender
	Subject                 string
	Body                    string
	BodyFormat              enums.BodyFormat
	BodyFull                string
	BodyHTML                string
	Attachments             []InboundAttachment
	ChannelMessageID        string
	ReplyToChannelMessageID string
	SentAt                  time.Time
	AutoGenerated           bool
	SpamVerdict             enums.SpamVerdict
	Source                  map[string]any
	IsTest                  bool
	Metadata                map[string]any
	AfterPersist            AfterPersist
}

/*
AfterPersist is a channel's hook into the inbox's transaction, called
with the conversation and the stored message.
*/
type AfterPersist func(ctx context.Context, tx *database.Tx, conv models.Conversation, msg models.Message) error

/*
InboundSender is who sent or took part in an inbound message: the
identities the channel claims for them, with their display details.
*/
type InboundSender struct {
	ContactID  *ids.UUID
	Identities []IdentityClaim
	Name       string
	Email      string
	Kind       enums.ContactKind
}

/*
IdentityClaim is one identity a channel claims for a sender. Verified
means the channel proved it, such as an email whose DKIM signature
aligns with its sender.
*/
type IdentityClaim struct {
	Type     enums.IdentityType
	Value    string
	Verified bool
}

/*
InboundAttachment is a file that came with an inbound message. Open
streams its content.
*/
type InboundAttachment struct {
	Filename    string
	ContentType string
	SizeBytes   int64
	Inline      bool
	ContentID   string
	Open        func(ctx context.Context) (io.ReadCloser, error)
}

/*
InboundResult is where an inbound message landed. Duplicate means it
had arrived before and nothing changed.
*/
type InboundResult struct {
	MessageID           ids.UUID
	ConversationID      ids.UUID
	ContactID           ids.UUID
	Duplicate           bool
	ConversationCreated bool
	Reopened            bool
	Spam                bool
}

/*
InboundReceiver takes inbound messages into the inbox.
*/
type InboundReceiver interface {
	/*
		ReceiveInboundMessage stores the message in its conversation,
		creating the contact and conversation it needs, in one
		transaction.
	*/
	ReceiveInboundMessage(ctx context.Context, msg InboundMessage) (InboundResult, error)
}
