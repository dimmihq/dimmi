package email_test

import (
	"testing"

	"github.com/stretchr/testify/assert"

	"github.com/dimmihq/dimmi/app/enums"
	"github.com/dimmihq/dimmi/app/integrations/email"
)

/*
header is a header for tests, by canonical field name.
*/
type header map[string]string

/*
Get returns the field's value.
*/
func (h header) Get(key string) string {
	return h[key]
}

func TestClassify(t *testing.T) {
	t.Parallel()

	t.Run("applies the first rule that matches", func(t *testing.T) {
		t.Parallel()

		none := header{}
		cases := []struct {
			name    string
			signals email.Signals
			want    enums.EmailClassification
		}{
			{"loop", email.Signals{Header: none, Loop: true, SystemNotice: true}, enums.EmailClassificationLoop},
			{"notice", email.Signals{Header: none, SystemNotice: true}, enums.EmailClassificationSystemNotice},
			{"complaint", email.Signals{Header: none, Complaint: true}, enums.EmailClassificationComplaint},
			{"bounce", email.Signals{Header: none, Bounce: true}, enums.EmailClassificationBounce},
			{
				"auto reply",
				email.Signals{Header: header{"Auto-Submitted": "auto-replied"}, Spam: true},
				enums.EmailClassificationAutoReply,
			},
			{"spam", email.Signals{Header: none, Spam: true, Member: true}, enums.EmailClassificationSpam},
			{
				"forwarded",
				email.Signals{Header: none, Member: true, Forwarded: true},
				enums.EmailClassificationForwarded,
			},
			{"test", email.Signals{Header: none, Member: true}, enums.EmailClassificationTest},
			{"list", email.Signals{Header: header{"List-Id": "<x.list>"}}, enums.EmailClassificationList},
			{"bulk", email.Signals{Header: header{"Precedence": "bulk"}}, enums.EmailClassificationBulk},
			{"noreply", email.Signals{Header: none, From: "no-reply@saas.test"}, enums.EmailClassificationNoreply},
			{
				"relay",
				email.Signals{Header: none, From: "no-reply@webflow.com", FormRelay: true},
				enums.EmailClassificationNormal,
			},
			{"normal", email.Signals{Header: none, From: "bob@customer.test"}, enums.EmailClassificationNormal},
		}

		for _, c := range cases {
			assert.Equal(t, c.want, email.Classify(c.signals), c.name)
		}
	})

	t.Run("recognizes automatic replies by their headers", func(t *testing.T) {
		t.Parallel()

		for _, h := range []header{
			{"Auto-Submitted": "auto-replied"},
			{"Auto-Submitted": "auto-replied (vacation)"},
			{"X-Autoreply": "yes"},
			{"X-Autorespond": "yes"},
			{"X-Autoresponse": "1"},
			{"X-Autoresponder": "true"},
			{"X-Mail-Autoreply": "yes"},
			{"X-Vacation": "on"},
			{"X-Loop": "yes"},
			{"X-Autogenerated": "Reply"},
			{"Precedence": "auto_reply"},
			{"X-Precedence": "auto_reply"},
			{"X-MS-Exchange-Inbox-Rules-Loop": "a@b.test"},
			{"X-MS-Exchange-Generated-Message-Source": "Mailbox Rules Agent"},
			{"X-POST-MessageClass": "9; Autoresponder"},
		} {
			assert.True(t, email.AutoReply(h), h)
		}
	})

	t.Run("takes a header that switches automatic replies off for a person", func(t *testing.T) {
		t.Parallel()

		for _, h := range []header{
			{"Auto-Submitted": "no"},
			{"X-Autoreply": "no"},
			{"X-Autorespond": "0"},
			{"X-Vacation": "false"},
			{},
		} {
			assert.False(t, email.AutoReply(h), h)
		}
	})

	t.Run("files a notification marked auto-generated like bulk mail, not as a reply", func(t *testing.T) {
		t.Parallel()

		generated := header{"Auto-Submitted": "auto-generated"}

		assert.False(t, email.AutoReply(generated))
		assert.True(t, email.AutoGenerated(generated))
		assert.True(t, email.AutoGenerated(header{"Auto-Submitted": "auto-notified"}))
		assert.False(t, email.AutoGenerated(header{"Auto-Submitted": "auto-replied"}))
		assert.False(t, email.AutoGenerated(header{"Auto-Submitted": "no"}))
		assert.Equal(t, enums.EmailClassificationBulk,
			email.Classify(email.Signals{Header: generated, From: "monitor@status.test"}))
		assert.Equal(t, enums.EmailClassificationNormal,
			email.Classify(email.Signals{Header: generated, From: "no-reply@webflow.com", FormRelay: true}))
	})

	t.Run("reads an automatic reply's subject only on a short message", func(t *testing.T) {
		t.Parallel()

		for _, subject := range []string{
			"Out of Office: back Monday", "Abwesenheitsnotiz", "Autosvar: Order", "Automatisk svar: Hej",
			"Автоответ: заказ", "AUTO: Away", "Abwesend: Bestellung", "Vacation reply", "AW: Abwesenheitsnotiz",
			"Re: Out of office",
		} {
			assert.True(t, email.AutoReplySubject(subject, 120), subject)
		}

		assert.False(t, email.AutoReplySubject("Out of office question", 4000))
		assert.False(t, email.AutoReplySubject("Refund for order 1042", 120))
	})

	t.Run("tells lists, bulk mail and no-reply senders apart", func(t *testing.T) {
		t.Parallel()

		assert.True(t, email.List(header{"Precedence": "list"}))
		assert.True(t, email.List(header{"X-Google-Group-Id": "1"}))
		assert.False(t, email.List(header{}))
		assert.True(t, email.Bulk(header{"Precedence": "junk"}))
		assert.True(t, email.Bulk(header{"List-Unsubscribe": "<u>", "X-SG-EID": "1"}))
		assert.False(t, email.Bulk(header{"List-Unsubscribe": "<u>"}))
		assert.False(t, email.Bulk(header{}))
		assert.True(t, email.Noreply("notifications@github.test"))
		assert.True(t, email.Noreply("donotreply+x@bank.test"))
		for _, from := range []string{
			"no_reply@shop.test", "no.reply@shop.test", "do_not_reply@shop.test", "x-noreply@shop.test",
			"info-noreply@shop.test", "postmaster@shop.test",
		} {
			assert.True(t, email.Noreply(from), from)
		}
		assert.False(t, email.Noreply("noreen@customer.test"))
		assert.False(t, email.Noreply("bob@customer.test"))
	})

	t.Run("reads a bounce without a report from its sender and subject", func(t *testing.T) {
		t.Parallel()

		none := header{}

		assert.True(t, email.BounceNotice(none, "", "x@y.test", "Undeliverable: Hello"))
		assert.True(t, email.BounceNotice(none, "a@b.test", "MAILER-DAEMON@mx.test", "Mail delivery failed"))
		assert.False(t, email.BounceNotice(none, "a@b.test", "bob@customer.test", "Undeliverable: Hello"))
		assert.False(t, email.BounceNotice(none, "", "x@y.test", "Hello"))
	})

	t.Run("reads a mail system's notice as a bounce whatever its subject says", func(t *testing.T) {
		t.Parallel()

		none := header{}

		assert.True(t, email.BounceNotice(none, "a@b.test", "postmaster@mx.test", "Nachricht"))
		assert.True(t, email.BounceNotice(none, "a@b.test", "mailer-daemon@mx.test", "Re: Hello"))
		assert.True(t, email.BounceNotice(header{"X-Failed-Recipients": "bob@customer.test"}, "a@b.test",
			"robot@mx.test", "Hello"))

		for _, subject := range []string{
			"Message not delivered", "Delivery has failed to these recipients", "Nicht zustellbar: Hallo",
			"Non recapitabile: Ciao", "No se puede entregar: Hola", "Não entregue: Olá",
			"Zustellung fehlgeschlagen", "Mail could not be delivered",
		} {
			assert.True(t, email.BounceNotice(none, "", "x@y.test", subject), subject)
		}
	})

	t.Run("reads a read receipt as an automatic reply", func(t *testing.T) {
		t.Parallel()

		receipt := header{"Content-Type": `multipart/report; report-type="disposition-notification"; boundary=b`}

		assert.True(t, email.AutoReply(receipt))
		assert.False(t, email.AutoReply(header{"Content-Type": "multipart/report; report-type=delivery-status"}))
	})
}
