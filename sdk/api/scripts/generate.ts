/*
 * Generates the API's types from its OpenAPI document with
 * openapi-typescript. Pass a file path or a URL, or nothing for a local
 * server's: node sdk/api/scripts/generate.ts [spec]. It writes
 * src/schema.ts, the paths and components openapi-fetch types its calls
 * with, and src/paging.ts, how each list that does not page by cursor
 * pages instead. openapi-typescript needs the TypeScript 5 compiler API,
 * which the repo's TypeScript 7 lacks, so it runs through pnpm dlx.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

type Spec = {
  info: { version: string };
  paths: Record<string, Record<string, { parameters?: { name: string; in: string }[] }>>;
};

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "..", "src");
const snapshot = path.join(here, "..", "..", "..", "tests", "contracts", "api_v1.openapi.json");
const source = process.argv[2] ?? (fs.existsSync(snapshot) ? snapshot : "http://localhost:8080/api/v1/openapi.json");

const text = /^https?:/.test(source) ? await (await fetch(source)).text() : fs.readFileSync(source, "utf8");
const spec: Spec = JSON.parse(text);

const banner = `/* Generated by sdk/api/scripts/generate.ts from the dimmi API ${spec.info.version}. Do not edit. */\n`;
const input = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "dimmi-openapi-")), "openapi.json");
fs.writeFileSync(input, text);
const schema = path.join(src, "schema.ts");
execFileSync(
  "pnpm",
  [
    "dlx",
    "--package=openapi-typescript@7.13.0",
    "--package=typescript@5.9.3",
    "openapi-typescript",
    input,
    "--alphabetize",
    "-o",
    schema,
  ],
  { stdio: "inherit" },
);
fs.writeFileSync(schema, banner + fs.readFileSync(schema, "utf8"));

const paging: Record<string, "offset" | "after"> = {};
for (const [route, methods] of Object.entries(spec.paths)) {
  const names = (methods.get?.parameters ?? []).filter((p) => p.in === "query").map((p) => p.name);
  if (names.includes("offset")) {
    paging[route] = "offset";
  } else if (names.includes("after")) {
    paging[route] = "after";
  }
}
fs.writeFileSync(
  path.join(src, "paging.ts"),
  `${banner}
export const API_VERSION = ${JSON.stringify(spec.info.version)};

/* Lists that page by offset or by an after cursor; every other list pages by cursor. */
export const paging: Record<string, "offset" | "after"> = ${JSON.stringify(paging, null, 2)};
`,
);

process.stdout.write(`wrote ${path.relative(process.cwd(), src)}/schema.ts and paging.ts\n`);
