/*
 * SourceLogo is a kind of source's mark on a neutral tile.
 */
export function SourceLogo({ logo, size = "md" }: { logo: string; size?: keyof typeof sizes }) {
  const mark = marks[logo] ?? RiBookOpenLine;
  const markClass = cx(sizes[size].mark, "shrink-0 text-text-primary");

  return (
    <span
      aria-hidden
      className={cx(
        "flex shrink-0 items-center justify-center bg-background-primary-default ring-1 ring-border-button-default ring-inset",
        sizes[size].box,
      )}
    >
      <Glyph mark={mark} className={markClass} />
    </span>
  );
}

/*
 * Glyph draws a mark: a component as it is, a path in the text colour.
 */
function Glyph({ mark: Mark, className }: { mark: Mark | string; className: string }) {
  if (typeof Mark === "string") {
    return (
      <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden className={className}>
        <path d={Mark} />
      </svg>
    );
  }

  return <Mark className={className} />;
}
